export type FilterCategory = 'All' | 'Clarity' | 'B&W' | 'Cinema' | 'Film' | 'Editorial' | 'Clean';

export interface FilterPreset {
  id: string;
  name: string;
  category: Exclude<FilterCategory, 'All'>;
  // Base filter components blended by intensity (0..1)
  brightness: number; // multiplier delta around 1 (e.g. 0.05)
  contrast: number; // multiplier delta around 1 (e.g. 0.25)
  saturate: number; // target saturation at 100% (1 = neutral, 0 = grayscale)
  grayscale: number; // 0..1
  sepia: number; // 0..1
  hueRotate: number; // deg
  clarityBoost?: number; // 0..1 hardware unsharp clarity / edge detail pass
  tintColor?: string; // optional rgba overlay for color grade
  tintBlend?: GlobalCompositeOperation;
  vignetteAdd?: number; // 0..0.6
  swatchCss: string;
}

